"""Сколько минут занимает визит — ОДИН ответ для всего приложения.

Появилось из отчёта 878. Одно и то же число считалось двумя способами:

* вердикт по заказу (`profitability_service.calculate_day_profitability`) брал всем
  поровну `day.planned_service_minutes` — 20 минут и обычному визиту, и работе на
  точке с приёмом 9:00–13:00;
* отчёт смены (`mobile_report_service`) давно считал честно, по длительности приёма.

Последствие было не косметическим. Занижение минут дня раздувает средний ₽/час, а
вердикт сравнивает новый заказ ИМЕННО со средним: для внезонных заказов планка равна
`max(средний ₽/час, порог)`. У человека с долгим приёмом планка становилась
непроходимой, и приложение объявляло невыгодным почти всё подряд.

Правило одно: есть у визита СВОЯ длительность — берём её, нет — плановую среднюю.
Ноль (и любое неположительное значение) считаем не «нулём минут», а незаполненным
полем: `Visit.service_minutes` по умолчанию `0.0`, и поверить нулю буквально значит
вернуть тот же перекос с другой стороны.

Смотрим именно на ДЛИТЕЛЬНОСТЬ, а не на `kind == "onsite"`, и это принципиально.
Цена фикс-времени (`fix_time_service`) строит контрфактический день, где тот же приём
идёт БЕЗ жёсткого времени: `replace(v, kind="field", planned_start_at=None)`. Приём при
этом остаётся четырёхчасовым — снят только жёсткий старт. Правило по виду решило бы,
что «свободный» приём длится 20 минут, и карточка объявила бы, что фикс-время съедает
2409 ₽/час на ровном месте. Заполняется поле только у работы на точке
(`mobile_visit_service.add_onsite_visit`), так что для обычных визитов это ровно то же
самое, что было.
"""

from __future__ import annotations

from app.models import Visit


def visit_service_minutes(visit: Visit, planned_service_minutes: float) -> float:
    """Минуты на адресе для ОДНОГО визита."""
    if visit.service_minutes > 0:
        return float(visit.service_minutes)
    return float(planned_service_minutes)


def total_service_minutes(visits: list[Visit], planned_service_minutes: float) -> float:
    """Минуты на адресах для списка визитов. Фильтрацию по статусу делает вызывающий."""
    return sum(visit_service_minutes(visit, planned_service_minutes) for visit in visits)
